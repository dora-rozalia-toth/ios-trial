import SwiftUI

struct GovernAIPanel: View {
    let panel: PanelState
    @State private var tab = 1   // 0 = Smart Assist, 1 = Insights

    var body: some View {
        VStack(spacing: 0) {
            header
            tabs
            crumb
            ScrollView {
                VStack(alignment: .leading, spacing: 0) {
                    meta
                    Text("Executive Summary").font(inter(17, .bold)).foregroundStyle(Palette.ink)
                        .padding(.top, 10).padding(.bottom, 10)
                    executiveCard
                    Text("Detailed Summary").font(inter(17, .bold)).foregroundStyle(Palette.ink)
                        .padding(.top, 10).padding(.bottom, 10)
                    detailedCard
                }
                .padding(.horizontal, 18)
                .padding(.bottom, 30)
            }
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .top)
        .background(Palette.panelBG)
        .overlay(alignment: .leading) { Hairline().frame(width: 1) }
    }

    // MARK: header

    private var header: some View {
        HStack(spacing: 9) {
            Image(systemName: "sparkles").font(.system(size: 22)).foregroundStyle(Palette.ai)
            Text("GovernAI").font(inter(20, .semibold)).foregroundStyle(Palette.ink)
            Spacer()
            IconButton(symbol: "ellipsis", label: "More", size: 38, glyph: 19) {}
            IconButton(symbol: "arrow.up.left.and.arrow.down.right", label: "Expand", size: 38, glyph: 18) {}
            // Active (highlighted) AI button — closes the panel.
            IconButton(symbol: "sparkles", label: "Close GovernAI",
                       size: 38, glyph: 19, tint: Palette.ai, filledBackground: Palette.aiTint) {
                panel.toggleGovernAI()
            }
        }
        .padding(.horizontal, 16)
        .padding(.top, 16)
        .padding(.bottom, 12)
    }

    private var tabs: some View {
        HStack(spacing: 26) {
            tabButton("Smart Assist", 0)
            tabButton("Insights", 1)
            Spacer()
        }
        .padding(.horizontal, 20)
        .overlay(alignment: .bottom) { Hairline() }
    }

    private func tabButton(_ title: String, _ index: Int) -> some View {
        Button { tab = index } label: {
            Text(title)
                .font(inter(15, .semibold))
                .foregroundStyle(tab == index ? Palette.ink : Palette.ink3)
                .padding(.bottom, 12)
                .overlay(alignment: .bottom) {
                    if tab == index { Rectangle().fill(Palette.ink).frame(height: 2) }
                }
        }
        .buttonStyle(.plain)
    }

    private var crumb: some View {
        HStack(spacing: 6) {
            Image(systemName: "chevron.backward").font(.system(size: 13, weight: .semibold))
            Text("Smart Summary").font(inter(14, .medium))
            Spacer()
        }
        .foregroundStyle(Palette.ink2)
        .padding(.horizontal, 18)
        .padding(.vertical, 12)
    }

    private var meta: some View {
        HStack {
            Text("Last updated on Apr 30, 2026, 11:24:40 AM")
                .font(inter(11)).foregroundStyle(Palette.ink2)
            Spacer()
            HStack(spacing: 5) {
                Image(systemName: "sparkles").font(.system(size: 11)).foregroundStyle(Palette.ai)
                Text("Generated by AI").font(inter(11)).foregroundStyle(Palette.ink2)
            }
        }
        .padding(.bottom, 14)
    }

    // MARK: cards

    private var executiveCard: some View {
        card {
            cardHeading("Financial reports")
            cardTopic("Topic")
            cardBody()
            cardHeading("Strategic updates").padding(.top, 14)
            cardTopic("Topic")
            cardBody()
            Button {} label: {
                HStack(spacing: 6) {
                    Image(systemName: "chevron.down").font(.system(size: 12, weight: .semibold))
                    Text("Show more").font(inter(13, .semibold))
                }
                .foregroundStyle(Palette.ink2)
                .frame(maxWidth: .infinity)
                .padding(.top, 10)
            }
            .buttonStyle(.plain)
        }
    }

    private var detailedCard: some View {
        card {
            cardHeading("Financial reports")
            cardTopic("Document - Q4 2024 Consolidated Financial Statements")
            cardBody()
            cardTopic("Subtopic of document").padding(.top, 14)
            cardBody()
        }
    }

    private func card<Content: View>(@ViewBuilder _ content: () -> Content) -> some View {
        VStack(alignment: .leading, spacing: 0) { content() }
            .padding(18)
            .frame(maxWidth: .infinity, alignment: .leading)
            .background(RoundedRectangle(cornerRadius: 14, style: .continuous).fill(Palette.surface))
            .overlay(RoundedRectangle(cornerRadius: 14, style: .continuous).strokeBorder(Palette.line, lineWidth: 1))
            .shadow(color: .black.opacity(0.04), radius: 2, y: 1)
            .padding(.bottom, 22)
    }

    private func cardHeading(_ t: String) -> some View {
        Text(t).font(inter(16, .bold)).foregroundStyle(Palette.ink).padding(.bottom, 6)
    }
    private func cardTopic(_ t: String) -> some View {
        Text(t).font(inter(13, .bold)).foregroundStyle(Color(hex: 0x3a3c42)).padding(.bottom, 5)
    }
    private func cardBody() -> some View {
        Text("The company reported a significant 12% year-over-year revenue increase to $4.2 billion. This robust growth was driven by strong demand across all product segments and geographic regions.")
            .font(inter(13)).foregroundStyle(Palette.ink2).lineSpacing(3)
            .fixedSize(horizontal: false, vertical: true)
            .padding(.bottom, 6)
    }
}
